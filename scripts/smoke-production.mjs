import { installCapture, enterFullscreen } from '../tests/helpers/capture.ts';
import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
  const errors = [], remoteRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
  page.on('request', request => { if (/^https?:/.test(request.url()) && !request.url().startsWith('http://127.0.0.1:4173/')) remoteRequests.push(request.url()); });
  await installCapture(page);
  await page.goto('http://127.0.0.1:4173/');
  await enterFullscreen(page);
  await page.getByRole('button', { name: 'Enter practice', exact: true }).click();
  const canvas = page.getByTestId('game-canvas');
  await expect(canvas).toBeFocused();
  await expect(page.getByTestId('fps')).toHaveText(/^\d+ FPS$/);
  await page.keyboard.down('KeyD');
  await page.waitForTimeout(250);
  await page.keyboard.up('KeyD');
  await page.keyboard.press('Space');
  await page.waitForTimeout(100);
  await page.keyboard.down('Space');
  await expect(page.getByTestId('hud-fuel')).not.toHaveText('100%');
  await page.mouse.move(1030, 410);
  const ammo = page.getByTestId('hud-ammo');
  await expect(canvas).toHaveCSS('cursor', 'none');
  await page.mouse.down({ button: 'right' });
  await page.waitForTimeout(250);
  await expect(ammo).toHaveText('12');
  await page.mouse.down({ button: 'left' });
  await expect(ammo).not.toHaveText('12');
  await page.mouse.up({ button: 'right' });
  const ammoAfterRightRelease = Number(await ammo.innerText());
  await expect.poll(async () => Number(await ammo.innerText())).toBeLessThan(ammoAfterRightRelease);
  await page.mouse.up({ button: 'left' });
  await page.waitForTimeout(100);
  const ammoAfterLeftRelease = await ammo.innerText();
  await page.waitForTimeout(250);
  await expect(ammo).toHaveText(ammoAfterLeftRelease);
  await page.keyboard.up('Space');
  await mkdir('docs/screenshots', { recursive: true });
  await page.screenshot({ path: 'docs/screenshots/09-production-retina.png' });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Resume', exact: true })).toBeVisible();
  await expect(page.getByTestId('fps')).toHaveText('— FPS');
  await page.keyboard.press('Shift+Tab');
  await expect(page.getByRole('button', { name: /Exit fullscreen/ })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button', { name: 'Resume', exact: true })).toBeFocused();
  await page.evaluate(() => document.exitFullscreen());
  await expect(page.getByTestId('fullscreen-gate')).toBeVisible();
  await page.getByRole('button', { name: 'Return to fullscreen', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Resume', exact: true })).toBeVisible();
  await expect(page.getByTestId('fps')).toHaveText('— FPS');
  await page.getByRole('button', { name: 'Resume', exact: true }).click();
  await expect(page.getByTestId('fps')).toHaveText(/^\d+ FPS$/);
  expect(await page.evaluate(() => window.__BURNHOP__)).toBeUndefined();
  expect(errors).toEqual([]);
  expect(remoteRequests).toEqual([]);
  const report = { productionSmoke: 'passed', viewport: '1440x900 @2x', externalRequests: remoteRequests.length, errors, developmentDiagnosticsAbsent: true, captureAPIs: 'emulated fullscreen, pointer lock and keyboard lock', controls: 'fullscreen welcome gate and deliberate practice entry, live FPS, move, jump, boot thrust, right-button aim without firing, both-button fire, release-right continued fire, release-left stop, pause, unavailable paused FPS, focus trap, fullscreen-loss gate, paused restoration and explicit resume' };
  await writeFile('docs/production-smoke.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally { await browser.close(); }
